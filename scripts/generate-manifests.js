import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const generateIndex = (dir) => {
    const fullDir = path.resolve(__dirname, '..', dir);

    if (!fs.existsSync(fullDir)) {
        console.warn(`Directory not found: ${fullDir}`);
        return;
    }

    const files = fs.readdirSync(fullDir).filter(file => file.endsWith('.ts') && file !== 'index.ts');

    const imports = files.map(file => `import './${file.replace('.ts', '')}';`).join('\n');
    const content = `// This file is auto-generated by scripts/generate-manifests.js
// Do not edit this file manually.
${imports}
`;

    fs.writeFileSync(path.join(fullDir, 'index.ts'), content);
    console.log(`Generated ${dir}/index.ts with ${files.length} imports.`);
};

console.log('Generating controller manifests...');
generateIndex('client/controllers');
generateIndex('server/controllers');
console.log('Done.');
